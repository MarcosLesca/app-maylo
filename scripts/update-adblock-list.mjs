// Regenerates the ad/tracker domain list bundled with modules/web-guard (S5).
// Usage (Node 22.18+ / 24, which strips TypeScript types): node scripts/update-adblock-list.mjs
//
// Only permissively licensed sources (MIT, CC BY) are merged; see
// modules/web-guard/THIRD_PARTY_NOTICES.md. StevenBlack's unified "hosts" file
// is NOT used as a whole because it also merges non-commercial and share-alike
// lists (MVPS CC BY-NC-SA, Dan Pollock, yoyo.org, KADhosts CC BY-SA).
// Parsing and compaction are the same functions the app tests (adblock.ts).
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compactBlocklist, parseBlocklist } from '../src/features/cast/browser/adblock.ts';

const SOURCES = [
  {
    name: "Steven Black's ad-hoc list",
    url: 'https://raw.githubusercontent.com/StevenBlack/hosts/master/data/StevenBlack/hosts',
    license: 'MIT',
  },
  { name: 'AdAway', url: 'https://raw.githubusercontent.com/AdAway/adaway.github.io/master/hosts.txt', license: 'CC BY 3.0' },
  {
    name: 'FadeMind add.2o7Net',
    url: 'https://raw.githubusercontent.com/FadeMind/hosts.extras/master/add.2o7Net/hosts',
    license: 'MIT',
  },
  {
    name: 'FadeMind UncheckyAds',
    url: 'https://raw.githubusercontent.com/FadeMind/hosts.extras/master/UncheckyAds/hosts',
    license: 'MIT',
  },
  { name: 'Tiuxo hostlist - ads', url: 'https://raw.githubusercontent.com/tiuxo/hosts/master/ads', license: 'CC BY 4.0' },
];

// Too few domains means a source changed format or failed silently: keep the old list.
const MIN_DOMAINS = 1000;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'modules/web-guard/android/src/main/assets/web-guard/blocklist.txt');

const domains = new Set();
for (const source of SOURCES) {
  const response = await fetch(source.url);
  if (!response.ok) throw new Error(`${source.name}: HTTP ${response.status}`);
  const found = parseBlocklist(await response.text());
  console.log(`${source.name}: ${found.size} domains`);
  for (const name of found) domains.add(name);
}

const list = compactBlocklist(domains);
if (list.length < MIN_DOMAINS) throw new Error(`Only ${list.length} domains; the list was not written.`);

const header = [
  '# MayLo web-guard ad/tracker domains. Generated by scripts/update-adblock-list.mjs; do not edit.',
  `# Generated: ${new Date().toISOString().slice(0, 10)}. Domains: ${list.length} (subdomains of listed ones removed).`,
  '# Sources (licenses in modules/web-guard/THIRD_PARTY_NOTICES.md):',
  ...SOURCES.map((source) => `#   ${source.name} (${source.license}): ${source.url}`),
];
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `${[...header, ...list].join('\n')}\n`);
console.log(`Wrote ${list.length} domains to ${output}`);
